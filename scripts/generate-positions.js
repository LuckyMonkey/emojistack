const fs = require("fs");
const path = require("path");
const positions = require("../data/positions");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src");

function formatCoord(value, unit) {
  const scaled = unit === "%" ? Number(value) * 100 : Number(value);
  const normalized = scaled.toFixed(2).replace(/\.?0+$/, "");
  return `${normalized}${unit || "em"}`;
}

function generatePositionsCss() {
  const direct = positions.find((entry) => entry.kind === "direct");
  const macro = positions.filter((entry) => entry.kind === "macro");
  const micro = positions.filter((entry) => entry.kind === "micro");

  const lines = [
    "/* This file is generated by scripts/generate-positions.js */",
    "/* direct center */",
    `.${direct.id} { --es-x: ${formatCoord(direct.x, direct.unit)}; --es-y: ${formatCoord(direct.y, direct.unit)}; --es-sub-size: 0.92; }`,
    "",
    "/* size tiers */",
    `${macro.map((entry) => `.${entry.id}`).join(",\n")} { --es-sub-size: 0.58; }`,
    "",
    `${micro.map((entry) => `.${entry.id}`).join(",\n")} { --es-sub-size: 0.36; }`,
    "",
    "/* macro grid */"
  ];

  macro.forEach((entry) => {
    lines.push(`.${entry.id} { --es-x: ${formatCoord(entry.x, entry.unit)}; --es-y: ${formatCoord(entry.y, entry.unit)}; }`);
  });

  lines.push("", "/* micro grid */");
  micro.forEach((entry) => {
    lines.push(`.${entry.id} { --es-x: ${formatCoord(entry.x, entry.unit)}; --es-y: ${formatCoord(entry.y, entry.unit)}; }`);
  });

  fs.writeFileSync(path.join(SRC, "positions.css"), `${lines.join("\n")}\n`, "utf8");
}

if (require.main === module) {
  generatePositionsCss();
}

module.exports = generatePositionsCss;
